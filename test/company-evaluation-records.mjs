import assert from 'node:assert/strict';
import { buildCompanyEvaluationCandidates as build } from '../lib/company-evaluation-records.js';
const now=new Date('2026-10-30T04:00:00Z');
const p={id:'p',tenant_id:'t',source_system:'enger',source_company_id:'c',company_id:'local',company_name:'同名',sent_at:'2026-10-01T00:00:00Z',status:'proposal_sent'};
const run=proposals=>build({tenantId:'t',proposals,now,complete:true});
assert.equal(run([p,p]).companies[0].sentCount,1);
assert.equal(run([p,{...p,tenant_id:'other'}]).companies[0].sentCount,1);
assert.equal(run([p,{...p,id:'q',source_company_id:'different'}]).companies.length,2);
assert.equal(run([{...p,source_company_id:null}]).unmappedCount,1);
assert.equal(run([{...p,sent_at:'2026-08-01T14:59:59Z'}]).companies.length,0);
assert.equal(run([{...p,sent_at:'2026-08-01T15:00:00Z'}]).companies.length,1);
assert.equal(run([{...p,sent_at:'2026-10-30T04:00:01Z'}]).companies.length,0);
assert.equal(run([{...p,delivery_kind:'blast'}]).companies.length,0);
assert.equal(run([{...p,deleted_at:now.toISOString()}]).companies.length,0);
assert.equal(run([{...p,archived_at:now.toISOString()}]).companies.length,1);
assert.equal(run([p,{...p,status:'won'}]).complete,false);
assert.equal(run(Array.from({length:15},(_,i)=>({...p,id:`p${i}`}))).companies[0].review.pendingCount,15);
assert.equal(run(Array.from({length:15},(_,i)=>({...p,id:`p${i}`}))).companies[0].review.enforceable,false);
const links=[{tenant_id:'t',source_system:'enger',source_company_id:'c',company_id:'local'}];
assert.equal(build({tenantId:'t',proposals:[{...p,source_company_id:null}],links,now,complete:true}).companies[0].sourceCompanyId,'c');
assert.equal(build({tenantId:'t',proposals:[p],links:[{...links[0],source_company_id:'wrong'}],now,complete:true}).unmappedCount,1);
assert.equal(build({tenantId:'t',proposals:[p],links:[links[0],{...links[0],source_company_id:'wrong'}],now,complete:true}).unmappedCount,1);
assert.equal(build({tenantId:'t',proposals:[p],meetings:[{tenant_id:'other',proposal_id:'p',kind:'meeting',result:'done',occurred_at:'2026-10-10T00:00:00Z'}],now,complete:true}).companies[0].meetingCount,0);
console.log('PASS company evaluation records: tenant, identity, no name merge, dedup/conflicts, window, pending, archived, blast/deleted exclusions');
