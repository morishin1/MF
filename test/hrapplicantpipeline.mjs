import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {OFFER_TYPES_PUBLIC, normalizeOfferTerms, trialEndOn} from '../lib/hr-offer-types.js';
import {eligible, startGuidance} from '../lib/hr-pdf-flow.js';
const context=vm.createContext({});
vm.runInContext(fs.readFileSync(new URL('../js/hr-applicant-list.js',import.meta.url),'utf8'),context);
const H=context.HRApplicantList;
const draft={id:'a',stage:'offer',status:'offer_draft_pending',decision:'hired',nextActionKey:'chooseOfferType',nextActionCta:'採用区分を選ぶ'};
assert.equal(H.view(draft).label,'合格通知の作成待ち');
assert.equal(H.view({...draft,overdue:true,alerts:[{label:'期限超過'}]}).label,'合格通知の作成待ち','overdue is not a replacement state');
for(const status of ['offer_sent','offer_viewed','offer_response_pending'])assert.equal(H.view({...draft,status,docs:{conditions:{notice:true}}}).stage,'agreement');
assert.equal(H.view({...draft,pdfFlow:{phase:'terms_preparing',acceptedAt:'2026-11-14'}}).stage,'terms');
assert.match(H.view({...draft,status:'accepted',handoffState:'done'}).href,/admin-hr\.html#agreement-a/);
assert.equal(H.pipeline({...draft,status:'offer_sent',docs:{conditions:{notice:false}}}).stage,'offer','an offer reply is separate from agreement on working terms');
assert.equal(H.pipeline({...draft,status:'accepted',handoffState:'ready'}).stage,'agreement','only the actual handoff advances to Office');
assert.equal(H.view({...draft,pdfFlow:{phase:'cancelled',acceptedAt:'2026-11-14'}}).stage,'closed');
assert.equal(H.accepted({...draft,pdfFlow:{phase:'cancelled',acceptedAt:'2026-11-14'}}),false);
assert.equal(H.view({...draft,status:'accepted',offerType:'training',nextActionKey:'advance'}).key,'advance','preserve the existing LMS route for training');
for(const ended of [{status:'passed'},{status:'declined'},{status:'position_closed'},{status:'done'},{pdfFlow:{phase:'cancelled'}},{pdfFlow:{phase:'declined'}},{pdfFlow:{phase:'joined'}}])assert.equal(H.isClosed({...draft,...ended}),true);
assert.equal(H.isClosed({...draft,status:'accepted'}),false,'keep pending Office handoff visible');
assert.equal(H.view({...draft,status:'done'}).label,'採用完了');
assert.equal(H.view({...draft,status:'done',leadCategory:'mugendojo'}).label,'対応完了');
let saved='';const storage={getItem:()=>saved,setItem:(_,s)=>saved=s};
const t=H.tracker(storage,'user1');t.update([draft]);assert.equal(t.count([draft]),0);
t.update([{...draft,note:'private note'}]);assert.equal(t.count([draft]),0,'notes do not become status news');
t.update([{...draft,status:'offer_send_pending'}]);assert.equal(t.count([draft]),1);
const t2=H.tracker(storage,'user1');assert.equal(t2.has('a'),true,'unread survives reload');
t2.read('a');assert.equal(t2.has('a'),false);
t2.update([{...draft,status:'offer_send_pending'},{...draft,id:'b'}]);assert.equal(t2.has('b'),true);
assert.ok(!saved.includes('private note'),'no personal details persisted');
assert.equal(trialEndOn('2026-11-19'),'2026-12-02');
assert.equal(trialEndOn('2028-02-20'),'2028-03-04');
assert.equal(trialEndOn('2026-12-25'),'2027-01-07');
assert.equal(trialEndOn('2026-02-30'),null);
const type=OFFER_TYPES_PUBLIC.find(t=>t.key==='trial_2weeks');assert.equal(type.label,'2週間トライアル');
assert.equal(type.fields.find(f=>f.key==='employmentType').required,true);
assert.equal(type.fields.find(f=>f.key==='contractPeriod').required,true,'trial does not silently decide contract duration');
assert.ok(!normalizeOfferTerms('trial_2weeks',{trialPeriod:'2週間'}).error);
const row={lead_category:'recruitment',offer_type:'trial_2weeks',stage:'offer',decision:'hired',status:'offer_draft_pending',join_date:'2026-11-19',employment_type:'契約社員'};
assert.equal(eligible(row),true);
assert.equal(eligible({...row,join_date:null}),false);
assert.equal(eligible({...row,employment_type:'業務委託'}),false);
assert.equal(startGuidance({...row,join_date:null}).action,'offerSetup');
console.log('HR pipeline: one state, agreement/Office routing, unread persistence and 2-week date boundaries PASS');
