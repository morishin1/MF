for(const row of [{taskTitle:"",goalText:"成果",doneWhen:""},{taskTitle:"提案",goalText:"",doneWhen:"完了した"}])
  assert.ok(requiredGoal(row).error);
assert.equal(goalStatus(null,{goal_text:"次の日の成果",done_when:"確認日を記録"},"2026-11-10"),"confirmed");
assert.equal(goalStatus({morning_at:"x",goal_image:"x",top_priority:"x"},null,"2026-11-09"),"missing");
assert.equal(shouldEnforceGoal("2026-11-08",null),false);
assert.equal(shouldEnforceGoal("2026-11-09",null),true);
assert.equal(shouldEnforceGoal("2026-11-09",{submitted_at:"x"}),false);
const api=read("api/nippo/index.js"),confirmApi=read("api/nippo/goal-confirm.js");
const coachApi=read("api/nippo/goal-coach.js"),page=read("nippo.html");
assert.doesNotMatch(api,/tomorrow_goal_required/);
assert.doesNotMatch(api,/error:"tomorrow_goal_required"/);
assert.match(api,/Tomorrow's goal is recommended but optional/);
assert.match(api,/body\?\.flowVersion===2/);
assert.match(api,/error:"outcome_required"/);
assert.match(api,/error:"reflection_required"/);
assert.match(api,/row.goal_image=currentGoal.done_when/);
assert.doesNotMatch(api,/row.goal_image=goalConfirmation.done_when/);
assert.match(api,/next_schedule_required/);
assert.match(api,/weekly_required/);
assert.match(confirmApi,/nextFocusDate\(reportDate\)/);
assert.match(confirmApi,/\.eq\("user_id",user.id\)\.eq\("work_date",date\)/);
assert.match(confirmApi,/target_already_submitted/);
assert.match(confirmApi,/source=week\?\.status==="active"/);
assert.doesNotMatch(confirmApi,/started_at:data.confirmed_at/);
assert.match(coachApi,/mode==="tomorrow"/);
assert.match(coachApi,/draftTomorrowGoalCoach/);
assert.match(coachApi,/loadTomorrowContext/);
assert.match(page,/AIがタスクと予定から提案/);
assert.match(page,/本人が確認して確定 → 提出へ/);
assert.match(page,/warningIfNoTomorrowGoal/);
