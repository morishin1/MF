import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {requiredGoal,goalStatus,shouldEnforceGoal,ROLLOUT_DATE} from "../lib/nippo-goal-confirm.js";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
assert.equal(ROLLOUT_DATE,"2026-11-09");
