import assert from "node:assert/strict";
import {requiredGoal,timingFor,goalStatus,shouldEnforceGoal,ROLLOUT_DATE} from "../lib/nippo-goal-confirm.js";
import {readFileSync} from "node:fs";
assert.equal(ROLLOUT_DATE,"2026-11-09");
assert.ok(requiredGoal({taskTitle:"A社の提案",goalText:"提案内容を判断できる",doneWhen:"提案書の送付と次回確認日を記録"}).goalText);
assert.ok(requiredGoal({taskTitle:"",goalText:"成果",doneWhen:""}).error);
assert.ok(requiredGoal({taskTitle:"A社の提案",goalText:"",doneWhen:"記録する"}).error);
assert.ok(requiredGoal({taskTitle:"A社の提案",goalText:"提案を確認する",doneWhen:""}).error);
assert.equal(timingFor("2026-11-10",{today:"2026-11-10",hour:9}),"on_time");
assert.equal(timingFor("2026-11-10",{today:"2026-11-10",hour:17}),"late");
assert.equal(timingFor("2026-11-09",{today:"2026-11-10",hour:9}),"late");
assert.equal(timingFor("2026-11-10",{today:"2026-11-10",hour:9,forceLate:true}),"late");
assert.equal(goalStatus({morning_at:"2026-11-08",goal_image:"完了",top_priority:"仕事"},null,"2026-11-08"),"legacy");
assert.equal(goalStatus({morning_at:"2026-11-09",goal_image:"完了",top_priority:"仕事"},null,"2026-11-09"),"missing");
assert.equal(goalStatus(null,{goal_text:"完了状態",done_when:"記録できた"},"2026-11-09"),"confirmed");
assert.equal(goalStatus(null,{goal_text:"",done_when:"記録できた"},"2026-11-09"),"missing");
assert.equal(shouldEnforceGoal("2026-11-08",null),false);
assert.equal(shouldEnforceGoal("2026-11-09",null),true);
assert.equal(shouldEnforceGoal("2026-11-09",{submitted_at:"2026-11-09T09:00:00Z"}),false);
const api=readFileSync(new URL("../api/nippo/index.js",import.meta.url),"utf8");
assert.match(api,/goal_confirmation_required/);
assert.match(api,/goalStatus\(existing,confirmed,date\)/);
assert.match(api,/row.goal_image=goalConfirmation.done_when/);
assert.match(api,/shouldEnforceGoal\(date,existing\)/);
assert.match(api,/existing\?\.goal_image/);
const confirmApi=readFileSync(new URL("../api/nippo/goal-confirm.js",import.meta.url),"utf8");
assert.match(confirmApi,/requireUser\(req,res\)/);
assert.match(confirmApi,/\.eq\("user_id",user.id\)\.eq\("work_date",date\)/);
assert.match(confirmApi,/return fail\(res,409,"already_submitted"/);
assert.match(confirmApi,/source=week\?\.status==="active"/);
assert.match(confirmApi,/timingFor\(date/);
const page=readFileSync(new URL("../nippo.html",import.meta.url),"utf8");
assert.match(page,/本人が確認して確定 → 次へ/);
assert.match(page,/AIにゴールを提案してもらう/);
assert.match(page,/朝に入力できず後から設定した/);
console.log("daily goal confirmation: validation, late/legacy handling, required gate and UI contracts passed");
