// Slackから本人タスクへ取り込む条件と署名・重複キーの検証（Slack未接続でも実行可能）。
import assert from "node:assert/strict";
import {createHmac} from "node:crypto";
import {verifySlackSignature,slackRequestTask} from "../lib/slack-task-ingest.js";
import {readFileSync} from "node:fs";
import {fileURLToPath} from "node:url";
import {dirname,join} from "node:path";
const root=dirname(dirname(fileURLToPath(import.meta.url)));
const read=f=>readFileSync(join(root,f),"utf8");

const now=Date.now();
const timestamp=String(Math.floor(now/1000));
const secret="unit-test-only";
const raw=JSON.stringify({type:"url_verification",challenge:"nonce"});
const signature="v0="+createHmac("sha256",secret).update("v0:"+timestamp+":"+raw).digest("hex");
assert.equal(verifySlackSignature({secret,body:raw,timestamp,signature,now}),true);
assert.equal(verifySlackSignature({secret,body:raw+" ",timestamp,signature,now}),false,"改竄");
assert.equal(verifySlackSignature({secret,body:raw,timestamp,signature:"v0=123",now}),false,"偽署名");
assert.equal(verifySlackSignature({secret,body:raw,timestamp,signature,now:now+301000}),false,"リプレイ拒否");
const conf={targetUserId:"UTARGET1",channels:["C0TASK123"],workspaceId:"TWORK1"};
const base={type:"message",user:"USENDER1",channel:"C0TASK123",ts:"1793750000.000123",
  text:"<@UTARGET1> 本日中にA社の返信案を確認してください"};
const good=slackRequestTask(base,conf);
assert.ok(good,"本人宛ての明示依頼");
assert.match(good.link,/^https:\/\/app\.slack\.com\/archives\/C0TASK123\/p1793750000000123$/);
assert.equal(good.priority,"high");
assert.equal(good.key,"slack:TWORK1:C0TASK123:1793750000.000123");
assert.equal(slackRequestTask(base,conf).key,good.key,"再配送してもキーが一致する");
assert.equal(slackRequestTask({...base,user:"UTARGET1"},conf),null,"本人の投稿は取り込まない");
assert.equal(slackRequestTask({...base,channel:"C0OTHER"},conf),null,"未許可チャンネルは取り込まない");
assert.equal(slackRequestTask({...base,bot_id:"B123"},conf),null,"botの投稿は取り込まない");
assert.equal(slackRequestTask({...base,subtype:"message_changed"},conf),null,"編集イベントは無視する");
assert.equal(slackRequestTask({...base,text:"<@UTARGET1> おはようございます"},conf),null,"雑談は取り込まない");
assert.equal(slackRequestTask({...base,text:"本日中にA社の返信案を確認してください"},conf),null,"本人への明示メンションなしは対象外");
assert.equal(slackRequestTask({...base,ts:"bad"},conf),null,"不正なID");
const urlSource=read("js/task-source-links.js");
new Function(urlSource);
const match=urlSource.match(/  function externalTaskLink\(raw\) \{[\s\S]*?\n  \}/)?.[0];
assert.ok(match,"タスク詳細にURL検証処理");
const url=new Function(match+"\nreturn externalTaskLink;")();
assert.equal(url("https://mail.google.com/mail/u/0/#inbox/abc").label,"Gmailを開く");
assert.equal(url("https://app.slack.com/archives/C1/p123").label,"Slackを開く");
assert.equal(url("https://example.com").label,"関連URLを開く");
assert.equal(url("javascript:alert(1)"),null,"javascriptスキームを拒否");
assert.equal(url("https://evil.com@real.com"),null,"認証情報入りリンクを拒否");
assert.match(urlSource,/a\.target = "_blank"/,"外部リンクは別タブで開く");
assert.match(urlSource,/a\.rel = "noopener noreferrer"/,"外部リンクから元画面を操作させない");
const home=read("home.html");
assert.match(home,/id="home-task-slack-btn"/,"Slack依頼の追加ボタン");
assert.match(home,/id="home-task-source-link"/,"Slack/GmailのURL入力");
assert.match(home,/sourceButton/,"タスク一覧からも元リンクを開ける");
const api=read("api/tasks/index.js");
assert.match(api,/if \(has\("link"\)\)/,"通常のタスク作成でもURLを保存できる");
assert.match(api,/v\.link=raw\|\|null/,"保存列は既存のgw_tasks.link");
const receiver=read("api/slack/task-events.js");
assert.match(receiver,/bodyParser:false/,"生本文で署名検証");
assert.match(receiver,/verifySlackSignature/,"署名確認後に処理");
assert.match(receiver,/SLACK_TASK_ALLOWED_CHANNEL_IDS/,"受信先を許可リストで制限");
assert.match(receiver,/23505/,"重複メッセージは再登録しない");
assert.match(receiver,/\.eq\("id",ownerEmployeeId\)/,"タスクの担当者を本人に固定");
console.log("PASS Gmail/Slackリンク、Slack署名・許可チャンネル・本人宛て・重複排除");
