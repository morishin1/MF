import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {renderEngerCompanyCsv,csvCell,enterpriseBucketLabel,ENGER_CSV_COLUMNS} from "../lib/sales-enger-csv.js";
const source = path => readFileSync(path,"utf8");
const api = source("api/sales/enger-company-export.js");
const client=source("js/sales-enger-export.js");
const nav=source("js/sales-layout.js");
const html=source("sales/companies.html");

assert.equal(renderEngerCompanyCsv([]).startsWith("\ufeff"),true,"Excel BOM");
assert.equal(renderEngerCompanyCsv([]).endsWith("\r\n"),true,"Excel CRLF");
assert.ok(ENGER_CSV_COLUMNS.some(([key])=>key==="email"));
assert.ok(ENGER_CSV_COLUMNS.some(([key])=>key==="phone"));
assert.ok(ENGER_CSV_COLUMNS.some(([key])=>key==="relationshipEvidence"));
assert.ok(ENGER_CSV_COLUMNS.some(([key])=>key==="oldPriority"));
assert.ok(ENGER_CSV_COLUMNS.some(([key])=>key==="id"));
assert.equal(csvCell("=SUM(1+2)"),'"\'=SUM(1+2)"',"Excel formula must be escaped");
assert.equal(csvCell(" @SUM(A1)"),'"\' @SUM(A1)"',"Excel formulas behind whitespace must be escaped");
assert.equal(csvCell("+12345"),'"\'+12345"');
assert.equal(csvCell("-3"),'"\'-3"');
assert.equal(csvCell("normal"),'"normal"');
assert.equal(csvCell('Company "A"'),'"Company ""A"""');
assert.equal(enterpriseBucketLabel("revive"),"掘り起こし");
const output=renderEngerCompanyCsv([{name:"テスト企業",id:"a-uuid",bucketLabel:"掘り起こし",email:"a@example.jp"}]);
assert.ok(output.includes('"テスト企業"')&&output.includes('"掘り起こし"'));
assert.equal(output.split("\r\n").filter(Boolean).length,2,"header and one data row");

assert.ok(api.includes("requireUser(req,res)")&&api.includes("canSell(ctx)")&&api.includes("isOwner(ctx)"));
assert.ok(api.includes("canAccessEightEngerDirectory(ctx)"),"must also restrict tenant");
assert.ok(api.includes('limit(0)')===false);
assert.ok(api.includes("MAX_ROWS=10000")&&api.includes("PAGE_SIZE=500"));
assert.ok(api.includes('from(VIEW)')&&api.includes("count.count")&&api.includes("all.length!==count.count"));
assert.ok(api.includes('from("companies")')&&api.includes("CONTACT_FIELDS"),"verified master contacts only");
assert.ok(api.includes("gwLog("),"audited bulk export");
assert.ok(api.includes('res.setHeader("Content-Disposition"'),"browser download response");
assert.ok(api.includes("res.write(csv.slice("),"streamed CSV export");
assert.ok(client.includes("window.API.getToken()")&&client.includes("Bearer "),"authenticated fetch");
assert.ok(client.includes('result.role === "owner"'),"hide buttons for nonowners");
assert.ok(client.includes('scope === "filtered"'),"filtered all rows supported");
assert.ok(client.includes('download("all")'),"complete enterprise list supported");
assert.ok(nav.includes("sales-enger-export.js")&&html.includes('id="enger-company-directory"'),"loaded only on enterprise screen");
assert.ok(!nav.includes('{ key: "attack", href: "/sales/attack.html"'),"no redundant Attack navigation");
assert.ok(nav.includes('active === "attack" ? "companies" : active'),"legacy route highlights Companies");
assert.ok(nav.includes('href: "/sales/companies.html"'),"companies header remains");
assert.ok(source("sales/attack.html").includes("アタック"),"legacy route is preserved");
console.log("PASS owner-only ENGER enterprise CSV + unified Companies navigation");
