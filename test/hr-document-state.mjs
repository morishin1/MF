import assert from 'node:assert/strict';import vm from 'node:vm';import fs from 'node:fs';
const c=vm.createContext({});vm.runInContext(fs.readFileSync(new URL('../js/hr-applicant-list.js',import.meta.url),'utf8'),c);const H=c.HRApplicantList;
const a={stage:'applied',status:'todo',employmentType:'契約社員',jobTitle:'営業',docs:{resume:true,reviews:{resume:'confirmed'}}};
const states=x=>Object.fromEntries(H.documents(x).map(d=>[d.key,d.state]));
assert.equal(states(a).resume,'done');assert.equal(states(a).work_history,'missing');assert.equal(states(a).skill_sheet,'na');assert.equal(states(a).notice,'na');
assert.equal(states({...a,docs:{resume:true}}).resume,'pending');
assert.equal(states({...a,docs:{resume:true,reviews:{resume:'defective'}}}).resume,'error');
assert.equal(states({...a,docs:null}).resume,'unknown');
assert.equal(states({...a,docs:{},talentCategory:'contractor',jobTitle:'エンジニア'}).resume,'na');
assert.equal(states({...a,talentCategory:'contractor',jobTitle:'エンジニア'}).skill_sheet,'missing');
assert.equal(states({...a,employmentType:'アルバイト'}).work_history,'na');
assert.equal(states({...a,stage:'offer',docs:{conditions:{notice:true,noticeConfirmed:true}}}).notice,'done');
assert.equal(states({...a,stage:'offer',pdfFlow:{phase:'terms_preparing'}}).notice,'unknown','a flow alone is not proof of a submitted PDF');
assert.equal(H.view({...a,status:'declined',currentTrial:{status:'active'}}).stage,'closed');
assert.equal(H.pipeline({...a,status:'done',employeeId:'employee'}).stage,'complete');
assert.equal(H.deadline({...a,decisionDueOn:'2026-11-15'},new Date('2026-11-14T01:00:00Z')).overdue,false);
assert.equal(H.deadline({...a,decisionDueOn:'2026-11-13'},new Date('2026-11-14T01:00:00Z')).overdue,true);
console.log('PASS: document required/optional/unknown, five states, original PDF facts, terminal hiring precedence and JST deadlines');
