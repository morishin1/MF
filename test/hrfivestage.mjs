import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { nextStatusFromRank, nextActionOf, laterStage, isOverdue } from '../lib/hr.js';
import { MOVE_STEP_KEYS, stepMoveOptions } from '../lib/hr-step-move.js';
const expected = ['applied','casual_interview','ceo_interview','offer','joining_scheduled'];
assert.deepEqual(MOVE_STEP_KEYS, expected);
assert.equal(nextStatusFromRank('A'),'ceo_interview_pending');
assert.equal(nextStatusFromRank('B'),'ceo_recommend_pending');
const legacy={stage:'ceo_recommend',status:'ceo_recommend_pending',rank:'A'};
const saved=JSON.stringify(legacy);
assert.equal(nextActionOf(legacy).action,'schedule');
assert.equal(nextActionOf(legacy).kind,'ceo');
assert.equal(nextActionOf({...legacy,rank:'B'}).kind,'casual');
assert.equal(laterStage('ceo_recommend','casual_interview'),'ceo_recommend');
const moves=stepMoveOptions(legacy,{canDecide:true});
assert.ok(!moves.options.some(o=>o.key==='ceo_recommend'));
assert.equal(JSON.stringify(legacy),saved);
assert.ok(stepMoveOptions({...legacy,status:'accepted'}).locked);
const html=fs.readFileSync(new URL('../hr/applicants.html',import.meta.url),'utf8');
const selection=html.match(/const SELECTION_STEPS = ([\s\S]*?);/)[1];
assert.deepEqual(JSON.parse(JSON.stringify(vm.runInNewContext(selection))).map(x=>x[0]),expected);
const stageMatch=vm.runInNewContext('('+html.match(/function stageMatch\(a, key\) \{[\s\S]*?\n  \}/)[0]+')');
assert.equal(stageMatch(legacy,'ceo_interview'),true);
assert.equal(stageMatch(legacy,'casual_interview'),false);
assert.equal(JSON.stringify(legacy),saved);
assert.ok(html.includes('旧「社長推薦」の記録を保持'));
assert.equal(isOverdue({decision:'hired',status:'offer_draft_pending',decision_due_on:'2026-11-01'},'2026-11-12'),true);
assert.equal(isOverdue({decision:'hired',status:'done',decision_due_on:'2026-11-01'},'2026-11-12'),false);
console.log('HR five-stage: transitions, B clarification, legacy history, five options, filters and overdue definition PASS');
